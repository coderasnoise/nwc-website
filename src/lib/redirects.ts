// Old WordPress URL -> new page. Never leave an old URL as a 404.
const FACE: Record<string, string> = {
  'facelift-rhytidectomy': 'deep-plane-facelift',
  'neck-lift': 'necklift',
  'eyelid-surgery-blepharoplasty': 'upper-eyelid',
  'forehead-lift-brow-lift': 'browlift',
};
const BODY = [
  'breast-augmentation', 'breast-lift-mastopexy', 'gynecomastia-surgery', 'liposuction', 'tummy-tuck-abdominoplasty',
  'arm-lift-brachioplasty', 'thigh-lift', 'buttock-augmentation-brazilian-butt-lift', 'buttock-lift', 'mommy-makeover',
];
const OTHER_SURGERY = [
  'rhinoplasty-nose-job', 'chin-augmentation', 'otoplasty-ear-surgery', 'dermal-fillers', 'fat-transfer-fat-grafting', 'labiaplasty', 'foot-aesthetic',
];

const EXACT: Record<string, string> = {
  '/sv': '/',
  '/about-us': '/doctor/',
  '/doctors': '/team/',
  '/doctors/dr-tolga-aksan': '/doctor/',
  '/patient-care-coordinators': '/team/',
  '/plasticsurgery': '/procedures/',
  '/other-treatments': '/procedures/',
  '/patients': '/reviews/',
  '/patient-guide': '/journey/',
  '/faq': '/',
  '/before-after': '/results/',
  '/hotel-transfer': '/journey/',
  '/prices': '/journey/',
};
for (const [old, slug] of Object.entries(FACE)) EXACT[`/plasticsurgery/${old}`] = `/procedures/${slug}/`;
for (const b of BODY) EXACT[`/plasticsurgery/${b}`] = '/procedures/body-surgery/';
for (const o of OTHER_SURGERY) EXACT[`/plasticsurgery/${o}`] = '/procedures/';

// Prefix rules (everything below the prefix), checked after exact matches.
const PREFIX: [string, string][] = [
  ['/about-us/', '/doctor/'],
  ['/doctors/', '/team/'],
  ['/patient-care-coordinators/', '/team/'],
  ['/plasticsurgery/', '/procedures/'],
  ['/other-treatments/', '/procedures/'],
  ['/patient-guide/', '/journey/'],
  ['/sv/', '/'],
];

const normalize = (p: string) => p.split('?')[0].split('#')[0].toLowerCase().replace(/\/+$/, '');

export function resolveLegacyPath(path: string): string | null {
  const n = normalize(path);
  if (n === '/sv') return '/';
  if (EXACT[n]) return EXACT[n];
  for (const [prefix, to] of PREFIX) if (`${n}/`.startsWith(prefix)) return to;
  return null;
}

export function redirectRules(): string {
  const lines: string[] = ['# Generated by scripts/build-redirects.mjs. Do not edit.'];
  for (const [from, to] of Object.entries(EXACT)) {
    lines.push(`${from} ${to} 301`, `${from}/ ${to} 301`);
  }
  for (const [prefix, to] of PREFIX) lines.push(`${prefix}* ${to} 301`);
  return lines.join('\n') + '\n';
}
